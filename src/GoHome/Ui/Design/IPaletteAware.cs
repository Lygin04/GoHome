namespace GoHome.Ui.Design;

/// <summary>
/// Элемент, которому при смене темы мало перерисовки.
/// </summary>
/// <remarks>
/// Большинству нарисованных контролов достаточно <see cref="Control.Invalidate()"/>: цвет
/// они спрашивают у <see cref="Palette.Current"/> прямо на отрисовке. Но фон элемент берёт
/// у родителя — <see cref="Control.BackColor"/> наследуется, — и там, где родитель рисует
/// себя не своим <c>BackColor</c> (окно, карточка), это свойство надо обновить отдельно.
/// Иначе кнопка внутри карточки затрёт свой угол цветом окна, а не карточки.
/// <para>
/// Тема применяется мгновенно и к уже открытым окнам, поэтому обход дерева нужен именно
/// в момент смены, а не только при создании.
/// </para>
/// </remarks>
internal interface IPaletteAware
{
    /// <summary>Перечитать палитру и обновить всё, что не пересчитывается на отрисовке.</summary>
    void RefreshPalette();
}
