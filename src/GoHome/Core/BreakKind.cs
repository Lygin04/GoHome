/// уход на обед и уход в переговорку выглядят для программы одинаково.
/// </summary>
public enum BreakKind
{
    /// <summary>Идёт в рабочее время: чай, туалет, переговорка, разговор в коридоре.</summary>
    Paid,

    /// <summary>Не идёт в рабочее время. За день такой отлучкой обычно бывает только обед.</summary>
    Unpaid,
}