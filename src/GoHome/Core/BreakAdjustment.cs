namespace GoHome.Core;

/// <summary>
/// Поправка к классификации одной отлучки. Живёт отдельно от отметок: в момент записи
/// тип отлучки неизвестен, поэтому журнал остаётся сырым, а поправки применяются на чтении.
/// </summary>
/// <param name="BreakAt">
/// Начало интервала, к которому привязана поправка. Файл дня правят руками, и поправка
/// вполне может перестать указывать на существующий интервал — тогда она просто игнорируется.
/// </param>
/// <param name="Kind">Как засчитывать этот интервал.</param>
/// <param name="Source">Кто поправил — для разбора журнала руками.</param>
public sealed record BreakAdjustment(DateTimeOffset BreakAt, BreakKind Kind, string? Source = null);