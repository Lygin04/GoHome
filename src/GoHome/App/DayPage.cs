using GoHome.Core;

namespace GoHome.App;

/// <summary>
/// Один день таким, каким его показывает форма дня.
/// </summary>
/// <remarks>
/// Расчёт и состояние файла приходят вместе, потому что читаются из одного файла за одно
/// обращение. Порознь их спрашивать пришлось бы дважды — на каждое обновление формы.
/// </remarks>
/// <param name="Summary">Расчёт дня.</param>
/// <param name="Unreadable">
/// Файл дня не разобрался. Показывать в нём нечего и править тем более нечего: правка
/// перезаписала бы файл, который не прочитался, и потеряла бы то, что в нём было.
/// </param>
/// <param name="Path">Путь к файлу дня — чтобы показать его в проводнике.</param>
/// <param name="Edited">
/// Начала отлучек, отметки которых правил человек через форму дня.
/// </param>
/// <remarks>
/// Правленые отмечаются отдельно от расчёта: в <see cref="DaySummary"/> происхождение
/// отметок не входит и входить не должно — оно ни на одну минуту не влияет. Но увидеть,
/// откуда взялось время, не совпадающее с фактом, человек должен.
/// </remarks>
/// <param name="PausedSince">
/// Начало отлучки, которая идёт прямо сейчас. В расчёт она не входит — чем окажется,
/// станет ясно на возвращении, — но показать её надо: без неё полоса нарисовала бы работу
/// от последней отметки до текущего момента.
/// </param>
public sealed record DayPage(
    DaySummary Summary,
    bool Unreadable,
    string Path,
    IReadOnlySet<DateTimeOffset> Edited,
    DateTimeOffset? PausedSince);
